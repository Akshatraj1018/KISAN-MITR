export function getFarmerName(targetLang = "hi") {
  let name = "";

  // 1. Direct key lookups (used by profile & dashboard)
  const directKeys = ["farmerName", "displayName", "userName"];
  for (const k of directKeys) {
    const val = localStorage.getItem(k);
    if (val && typeof val === "string" && val.trim()) {
      name = val.trim();
      break;
    }
  }

  // 2. Profile JSON object lookups
  if (!name) {
    const jsonKeys = ["farmerProfile", "userProfile", "agroUser", "farmer_profile"];
    for (const k of jsonKeys) {
      try {
        const raw = localStorage.getItem(k);
        if (raw) {
          const parsed = JSON.parse(raw);
          const candidate = parsed.fullName || parsed.name || parsed.displayName;
          if (candidate && typeof candidate === "string" && candidate.trim()) {
            name = candidate.trim();
            break;
          }
        }
      } catch {}
    }
  }

  // Clean any trailing role tag like " (Farmer)"
  if (name) {
    name = name.replace(/\s*\([^)]*\)/g, "").trim();
  }

  // Default respectful neutral address if visitor is not logged in
  if (!name) {
    if (targetLang === "hi") return "किसान भाई";
    if (targetLang === "or") return "ଚାଷୀ ଭାଇ";
    if (targetLang === "bn") return "কৃষক বন্ধু";
    if (targetLang === "pa") return "ਕਿਸਾਨ ਵੀਰ";
    return "Farmer friend";
  }

  // Respectful script transliteration for common names entered in Latin
  const lower = name.toLowerCase();
  if (lower === "rameshwar singh" || lower === "rameshwar") {
    if (targetLang === "hi") return "रामेश्वर सिंह";
    if (targetLang === "or") return "ରାମେଶ୍ୱର ସିଂହ";
    if (targetLang === "bn") return "রামেশ্বর সিংহ";
    return name;
  }
  if (lower === "vivek" || lower === "vivek singh" || lower === "vivek kumar") {
    if (targetLang === "hi") return name.replace(/vivek/i, "विवेक").replace(/singh/i, "सिंह").replace(/kumar/i, "कुमार");
    if (targetLang === "or") return name.replace(/vivek/i, "ବିବେକ").replace(/singh/i, "ସିଂହ").replace(/kumar/i, "କୁମାର");
    if (targetLang === "bn") return name.replace(/vivek/i, "বিবেক").replace(/singh/i, "সিংহ").replace(/kumar/i, "কুমার");
    return name;
  }
  if (lower === "akshat" || lower === "akshat raj") {
    if (targetLang === "hi") return "अक्षत";
    if (targetLang === "or") return "ଅକ୍ଷତ";
    if (targetLang === "bn") return "অক্ষত";
    if (targetLang === "pa") return "ਅਕਸ਼ਤ";
    return name;
  }

  return name;
}

